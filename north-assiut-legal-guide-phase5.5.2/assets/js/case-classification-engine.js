  function getArticlePool(){
    try {
      if (typeof allAppData === "function") return allAppData() || [];
      if (Array.isArray(window.EXECUTIVE_ARTICLES)) return window.EXECUTIVE_ARTICLES;
    } catch {}
    return [];
  }

  function articleText(article){
    return [article.lawName, article.lawNumber, article.articleNumber, article.shortTitle, article.topic, article.officialText, article.practicalExplanation, article.executivePoints, article.hypotheticalExamples, article.correctAction, article.commonErrors, article.searchText, (article.keywords||[]).join(" ")].join(" ");
  }

  function findArticlesForRule(rule, text, max=5){
    const pool = getArticlePool();
    const query = `${rule.title} ${rule.tags.join(" ")} ${text}`;
    let selected = [];
    if (typeof selectRelevantArticles === "function") {
      selected = selectRelevantArticles(query, 18);
    }
    const byHints = pool.filter(article => {
      const num = String(article.articleNumber || "");
      return (rule.articleHints || []).some(h => num.includes(h));
    });
    const merged = [];
    const seen = new Set();
    for (const article of [...byHints, ...selected]) {
      if (!article || seen.has(article.id)) continue;
      const searchable = norm(articleText(article));
      const thematic = countAny(searchable, rule.tags);
      const hint = (rule.articleHints || []).some(h => String(article.articleNumber || "").includes(h));
      if (hint || thematic > 0 || merged.length < 2) {
        merged.push(article); seen.add(article.id);
      }
      if (merged.length >= max) break;
    }
    return merged;
  }

  function scoreRule(rule, normalizedText){
    const tagScore = countAny(normalizedText, rule.tags) * 2;
    const strongScore = countAny(normalizedText, rule.strong || []) * 5;
    const dependsBonus = 0;
    return tagScore + strongScore + dependsBonus;
  }

  function levelFromScore(score){
    if (score >= 16) return "مرتفع";
    if (score >= 8) return "محتمل";
    return "يحتاج فحصًا إضافيًا";
  }

  function detectThemes(rules){
    return [...new Set(rules.map(r => r.domain))];
  }

  function buildCaseLegalPreAnalysis(text, options={}){
    const original = safeText(text);
    const normalized = norm(original);
    const words = tokenize(original);
    const matchedTemplates = matchTemplates(normalized);
    const scored = RULES
      .map(rule => ({rule, score: scoreRule(rule, normalized)}))
      .filter(item => item.score > 0)
      .sort((a,b)=> b.score - a.score);

    let top = scored.slice(0, 5);
    if (!top.length && typeof selectRelevantArticles === "function") {
      const selected = selectRelevantArticles(original, 8);
      if (selected.length) {
        top = [{rule:{id:"general",domain:"تحليل عام",title:"تكييف يحتاج فحصًا من واقع المواد الأقرب",tags:words,articleHints:[],reasons:["تم العثور على مواد قريبة من ألفاظ الواقعة، لكن الواقعة تحتاج تحديدًا موضوعيًا أكبر."],requiredProof:["تحديد نوع الجريمة والنتيجة والأدلة الأساسية."],checklist:["استكمال عناصر الواقعة والرجوع للمواد المرتبطة."],warnings:["لا توجد كلمات مفتاحية كافية لترجيح وصف محدد." ]}, score:3}];
      }
    }

    const classifications = top.map(({rule, score}) => {
      const articles = findArticlesForRule(rule, original, 5);
      return {
        id: rule.id,
        title: rule.title,
        domain: rule.domain,
        level: levelFromScore(score),
        score,
        reasons: rule.reasons || [],
        confirmedElements: (rule.strong || []).filter(w => normalized.includes(norm(w))).slice(0,5).map(w => `ورد بالواقعة ما يشير إلى: ${w}`),
        uncertainElements: rule.requiredProof || [],
        requiredProof: rule.requiredProof || [],
        checklist: rule.checklist || [],
        warnings: rule.warnings || [],
        relatedArticles: articles.map(a => ({id:a.id, lawName:a.lawName, articleNumber:a.articleNumber, shortTitle:a.shortTitle, topic:a.topic}))
      };
    });

    const allCheck = [...new Set(classifications.flatMap(c => c.checklist || []))].slice(0,12);
    const allWarnings = [...new Set(classifications.flatMap(c => c.warnings || []))].slice(0,10);
    const allQuestions = [...new Set(classifications.flatMap(c => c.requiredProof || []))].slice(0,10);
    const allArticles = [];
    const seen = new Set();
    for (const c of classifications) {
      for (const a of c.relatedArticles || []) {
        if (!seen.has(a.id)) { allArticles.push(a); seen.add(a.id); }
      }
    }

    const confidence = classifications.length >= 2 ? "متوسطة" : (classifications.length ? "أولية" : "منخفضة");
    return {
      version: ENGINE_VERSION,
      inputLength: original.length,
      detectedThemes: detectThemes(top.map(x=>x.rule)),
      matchedTemplates,
      classifications,
      missingQuestions: allQuestions,
      investigationChecklist: allCheck,
      warnings: allWarnings,
      relatedArticles: allArticles.slice(0,12),
      confidence,
      note: "هذا ترشيح مبدئي آلي يساعد في ترتيب التفكير ولا يغني عن فحص الأوراق والتقدير القضائي."
    };
  }

  function caseLegalPreAnalysisToPrompt(pre){
    if (!pre) return "لا يوجد تحليل محلي مبدئي.";
    return JSON.stringify({
      detectedThemes: pre.detectedThemes,
      specializedTemplates: pre.matchedTemplates || [],
      preliminaryClassifications: (pre.classifications || []).map(c => ({
        title: c.title,
        domain: c.domain,
        level: c.level,
        reasons: c.reasons,
        requiredProof: c.requiredProof,
        suggestedArticles: (c.relatedArticles || []).map(a => `${a.lawName || ""} — مادة ${a.articleNumber || ""} — ${a.shortTitle || ""}`)
      })),
      missingQuestions: pre.missingQuestions,
      investigationChecklist: pre.investigationChecklist,
      warnings: pre.warnings,
      relatedArticles: (pre.relatedArticles || []).map(a => `${a.lawName || ""} — مادة ${a.articleNumber || ""} — ${a.shortTitle || ""}`),
      confidence: pre.confidence,
      note: pre.note
    }, null, 2);
  }

  window.SAND_CASE_CLASSIFICATION_ENGINE = { build: buildCaseLegalPreAnalysis, toPrompt: caseLegalPreAnalysisToPrompt, version: ENGINE_VERSION };
  window.buildCaseLegalPreAnalysis = buildCaseLegalPreAnalysis;
  window.caseLegalPreAnalysisToPrompt = caseLegalPreAnalysisToPrompt;
